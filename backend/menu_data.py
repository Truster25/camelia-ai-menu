"""The real Camellia menu, transcribed from photographs of the printed menu.

Every name, price and description here comes from the restaurant's own menu.
Nothing is invented except the fields the menu does not print: the dietary
labels, spice levels and prep times.

Those are marked conservatively and deliberately. A dietary label is a promise
to a customer with an allergy or a religious requirement, and the printed menu
does not state halal status, gluten content or vegan suitability for anything.
So:

  * `vegan` is only set where the ingredients listed cannot contain an animal
    product, for example a single-fruit juice.
  * `vegetarian` is set where the listed ingredients contain no meat or fish.
  * `halal` is never set. Camellia's certificate status is unknown, and
    guessing it would be the single most damaging thing this file could do.
  * `gluten_free` is only set where nothing baked, fried in batter or thickened
    appears.

The restaurant should confirm every one of these before the site goes to
customers. `docs/DIETARY-REVIEW.md` lists exactly what needs signing off.
"""
from __future__ import annotations


def d(
    name: str,
    category: str,
    price: int,
    description: str,
    *,
    veg: bool = False,
    vegan: bool = False,
    gf: bool = False,
    spice: int = 0,
    ingredients: str = "",
    occasions: str = "casual,family",
    cuisine: str = "any",
    prep: int = 15,
    calories: int = 0,
    pop: int = 50,
    signature: bool = False,
    allergens: str = "",
) -> dict:
    """One dish, with the menu's facts and the site's metadata kept apart."""
    return {
        "name": name,
        "category": category,
        "price": price,
        "description": description,
        "is_vegetarian": veg,
        "is_vegan": vegan,
        # Never asserted. See the note at the top of this file.
        "is_halal": False,
        "is_gluten_free": gf,
        "spice_level": spice,
        "ingredients": ingredients,
        "occasions": occasions,
        "cuisine": cuisine,
        "prep_minutes": prep,
        "calories": calories,
        "popularity_seed": pop,
        "is_signature": signature,
        "allergens": allergens,
    }


